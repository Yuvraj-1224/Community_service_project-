def _ensure_fonts() -> None:
    global _fonts_ready
    if _fonts_ready:
        return
    pdfmetrics.registerFont(TTFont("Noto", str(FONT_DIR / "NotoSansDevanagari-Regular.ttf")))
    pdfmetrics.registerFont(TTFont("Noto-Bold", str(FONT_DIR / "NotoSansDevanagari-Bold.ttf")))
    pdfmetrics.registerFontFamily("Noto", normal="Noto", bold="Noto-Bold", italic="Noto", boldItalic="Noto-Bold")
    _fonts_ready = True


def build_report(scan: Scan, disease: Disease | None, lang: str = "en") -> bytes:
    _ensure_fonts()
    lang = "hi" if lang == "hi" else "en"
    L = LABELS[lang]
    hi = lang == "hi"

    body = ParagraphStyle("body", fontName="Noto", fontSize=10, leading=15)
    small = ParagraphStyle("small", parent=body, fontSize=8.5, leading=12, textColor=colors.HexColor("#4b5563"))
    h1 = ParagraphStyle("h1", fontName="Noto-Bold", fontSize=18, leading=24, textColor=GREEN)
    h2 = ParagraphStyle("h2", fontName="Noto-Bold", fontSize=12.5, leading=18, textColor=GREEN, spaceBefore=8, spaceAfter=3)
    brand = ParagraphStyle("brand", fontName="Noto-Bold", fontSize=22, leading=26, textColor=GREEN, alignment=TA_CENTER)

    def P(text, style=body):
        return Paragraph(escape(str(text)), style)

    def pick(en, hi_val):
        return hi_val if hi and hi_val else en

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=14 * mm,
                            bottomMargin=14 * mm, title=f"AgroVision AI - Scan {scan.id}", author="AgroVision AI")
    story = [Paragraph("AgroVision AI", brand), Spacer(1, 2), Paragraph(escape(L["title"]), ParagraphStyle("t", parent=h1, alignment=TA_CENTER, fontSize=14)), Spacer(1, 8)]

    created = scan.created_at if scan.created_at.tzinfo else scan.created_at.replace(tzinfo=timezone.utc)
    local = created.astimezone(ZoneInfo("Asia/Kolkata")).strftime("%d %b %Y, %I:%M %p IST")
    identified = scan.result_status == "identified"
    crop = pick(scan.crop_name, disease.crop_name_hi if disease else None) if scan.crop_name else L["not_identified"]
    dname = pick(scan.disease_name, disease.disease_name_hi if disease else None) if identified else L["not_identified"]

    rows = [
        [P(L["scan_id"], body), P(f"#{scan.id}")],
        [P(L["date"]), P(local)],
        [P(L["crop"]), P(crop)],
        [P(L["disease"]), P(dname)],
        [P(L["confidence"]), P(f"{scan.confidence * 100:.1f}%")],
        [P(L["status"]), P(L.get(scan.health_status, scan.health_status))],
        [P(L["model"]), P(scan.model_version)],
    ]
    info = Table(rows, colWidths=[38 * mm, 62 * mm])
    info.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), LIGHT), ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#bbf7d0")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))

    img_cell = P("")
    try:
        p = resolve_upload_path(scan.image_path)
        if p.exists():
            img = RLImage(str(p))
            ratio = img.imageHeight / float(img.imageWidth)
            w = 70 * mm
            img.drawWidth, img.drawHeight = w, min(w * ratio, 90 * mm)
            img_cell = img
    except Exception:  # image is optional in the report
        pass

    top = Table([[img_cell, info]], colWidths=[76 * mm, 102 * mm])
    top.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [top, Spacer(1, 8)]

    def bullets(items):
        return ListFlowable([ListItem(P(i), leftIndent=10) for i in items], bulletType="bullet", start="•", leftIndent=12)

    if identified and disease:
        desc = pick(disease.description, disease.description_hi)
        if desc:
            story.append(P(desc))
        for key, en_list, hi_list in (
            ("symptoms", disease.symptoms, disease.symptoms_hi),
            ("causes", disease.causes, disease.causes_hi),
            ("treatment", disease.treatment, disease.treatment_hi),
            ("prevention", disease.prevention, disease.prevention_hi),
        ):
            items = (hi_list if hi and hi_list else en_list) or []
            if items:
                story += [Paragraph(escape(L[key]), h2), bullets(items)]
    else:
        story.append(P(L["uncertain_msg"]))

    story += [Spacer(1, 12), P(L["disclaimer"], small)]
    doc.build(story)
    return buf.getvalue()
